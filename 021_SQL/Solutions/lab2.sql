-- 1. Create a BEFORE UPDATE trigger on address table to set last_update = NOW() 
-- whenever a row is changed.

DELIMITER /

create trigger update_last_time
before update on address
for each row
begin
	set new.last_update = now();
end /

DELIMITER ;






 -- 2. Create a trigger to prevent an UPDATE to the staff table if the username is changed to 'admin'
 
DELIMITER /
create trigger prevent_update
before update on staff
for each row
begin
	if new.username = "admin" then
		signal sqlstate '45000'
        set message_text = "update is denied.";
	end if;
end /
DELIMITER ;








-- 3. Create a BEFORE INSERT trigger on the customer table to ensure that any email address 
-- entered contains both an @ and a . symbol.

DELIMITER /
create trigger customer_email_validation
before insert on customer
for each row
begin
	if new.email not REGEXP '^[^@]+@[^@]+\.[^@]{2,}$' then
		signal sqlstate '45000'
        set message_text = "wrong email formate.";
	end if;
end /
DELIMITER ;








-- 4. Create a table film_price_history. Create an AFTER UPDATE trigger on the film table 
-- that records the old price, new price, and change date whenever the rental_rate is modified

DELIMITER /
create trigger film_price_history
after update on film
for each row
begin
	if old.rental_rate <> new.rental_rate then
		insert into film_price_history(film_id, old_rental_rate, new_rental_rate, change_date)
        value (new.film_id, old.rental_rate, new.rental_rate, now());
    end if;
end /
DELIMITER ;